function toLocalizedWord(raw: RawWord, language: PracticeLanguage): Word {
  const { pt, ...rest } = raw;
  if (language === 'fr') {
    const frTerm = FR_TERMS_BY_ID[raw.id];
    return { ...rest, term: frTerm ?? pt, language };
  }
  return { ...rest, term: pt, language, audioUrl: `/audio/pt/${raw.id}.mp3` };
}

function shuffle<T>(arr: T[]): T[] {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function resolveWordType(word: Pick<Word, 'wordType' | 'en'>): string | undefined {
  if (word.wordType) return word.wordType;
  const normalizedEn = word.en?.trim().toLocaleLowerCase();
  if (
    normalizedEn &&
    (normalizedEn.startsWith('to ') ||
      normalizedEn.includes('/to ') ||
      normalizedEn.startsWith("let's "))
  ) {
    return 'verb';
  }
  return undefined;
}

function getAllowedDistractorTypes(correctWord: Word | undefined): string[] {
  const type = resolveWordType(correctWord ?? {});
  if (type === 'noun') return ['noun'];
  if (type === 'verb') return ['verb'];
  if (type === 'adjective') return ['adjective'];
  return [];
}

/** Returns all words. In v1 this is the "deck". */
export function getWords(): Word[] {
  return WORDS.map((word) => toLocalizedWord(word, 'pt'));
}

/** Returns word by id, or undefined. */
export function getWordById(id: string): Word | undefined {
  const raw = WORDS.find((w) => w.id === id);
  return raw ? toLocalizedWord(raw, 'pt') : undefined;
}

/** Total number of words in the deck (for slider max = "all"). */
export const DECK_LENGTH = WORDS.length;

/** Returns a new shuffled array of word IDs for session start. If maxCount is given, returns up to that many; otherwise all. */
export function getShuffledWordIds(maxCount?: number): string[] {
  const ids = shuffle(WORDS.map((w) => w.id));
  return maxCount != null ? ids.slice(0, maxCount) : ids;
}

export function getWordsForLanguage(language: PracticeLanguage): Word[] {
  return WORDS.map((word) => toLocalizedWord(word, language));
}

export function getWordByIdForLanguage(
  id: string,
  language: PracticeLanguage
): Word | undefined {
  const raw = WORDS.find((w) => w.id === id);
  return raw ? toLocalizedWord(raw, language) : undefined;
}

/** Pick N random distractors (other words' en) excluding excludeEn. */
export function getDistractors(
  correctEn: string,
  count: number,
  excludeId?: string,
  wordPool: Word[] = getWords(),
  correctWord?: Word
): string[] {
  const others = wordPool.filter(
    (w) => w.en && w.en !== correctEn && w.id !== excludeId
  );
  const allowedTypes = getAllowedDistractorTypes(correctWord);

  const enValues = new Set<string>();
  if (allowedTypes.length > 0) {
    const byType = new Map<string, Word[]>();
    for (const type of allowedTypes) {
      byType.set(type, shuffle(others.filter((w) => resolveWordType(w) === type)));
    }

    let addedInPass = true;
    while (enValues.size < count && addedInPass) {
      addedInPass = false;
      for (const type of allowedTypes) {
        const bucket = byType.get(type);
        if (!bucket || bucket.length === 0) continue;
        const nextWord = bucket.pop();
        if (!nextWord?.en || enValues.has(nextWord.en)) continue;
        enValues.add(nextWord.en);
        addedInPass = true;
        if (enValues.size >= count) break;
      }
    }
  }

  if (enValues.size < count) {
    for (const w of shuffle(others)) {
      if (!w.en || enValues.has(w.en)) continue;
      enValues.add(w.en);
      if (enValues.size >= count) break;
    }
  }
  return [...enValues].slice(0, count);
}
